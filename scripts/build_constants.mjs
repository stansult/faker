import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import validationConstants from "../shared/validationConstants.cjs";

const {
  MAX_WORD_LENGTH,
  MAX_NAME_LENGTH,
  ROOM_CODE_LENGTH,
  ROOM_ACTIVE_TTL_HOURS,
  VOTE_TOTAL_SECONDS,
  VOTE_FINAL_SECONDS
} = validationConstants;

function parseEnvInt(env, name, fallback) {
  const raw = env[name];
  if (!raw) return fallback;
  const value = Number.parseInt(raw, 10);
  return Number.isFinite(value) ? value : fallback;
}

export function renderValidationConstants(env = process.env) {
  const voteTotalSeconds = parseEnvInt(env, "VOTE_TOTAL_SECONDS", VOTE_TOTAL_SECONDS);
  const voteFinalSeconds = parseEnvInt(env, "VOTE_FINAL_SECONDS", VOTE_FINAL_SECONDS);

  return `// Generated by scripts/build_constants.mjs. Do not edit by hand.
window.VALIDATION_CONSTANTS = ${JSON.stringify({
  MAX_WORD_LENGTH,
  MAX_NAME_LENGTH,
  ROOM_CODE_LENGTH,
  ROOM_ACTIVE_TTL_HOURS,
  VOTE_TOTAL_SECONDS: voteTotalSeconds,
  VOTE_FINAL_SECONDS: voteFinalSeconds
}, null, 2)};
`;
}

export function writeValidationConstants(outputPath = resolve("validationConstants.js"), env) {
  writeFileSync(outputPath, renderValidationConstants(env), "utf8");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeValidationConstants();
}
